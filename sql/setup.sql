-- Run as SYSDBA. Minimal privileges the scripts need. Replace CHANGE_ME.
ALTER SESSION SET CONTAINER = FREEPDB1;
CREATE USER ai_lab IDENTIFIED BY "CHANGE_ME" QUOTA UNLIMITED ON users;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW TO ai_lab;
CREATE USER ai_user IDENTIFIED BY "CHANGE_ME" QUOTA UNLIMITED ON users;
GRANT DB_DEVELOPER_ROLE TO ai_user;
CREATE OR REPLACE DIRECTORY DM_DUMP AS '/tmp';
GRANT READ, WRITE ON DIRECTORY DM_DUMP TO ai_user;
GRANT CREATE MINING MODEL TO ai_user;
GRANT SELECT ON sys.v_$mystat TO ai_lab;
GRANT SELECT ON sys.v_$statname TO ai_lab;
